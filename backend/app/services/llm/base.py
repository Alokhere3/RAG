"""Base interface and typed contracts for LLM inference providers."""

from abc import ABC, abstractmethod
from typing import List, Optional
from pydantic import BaseModel, Field


class LlmMessage(BaseModel):
    """Single prompt or conversational turn message."""

    role: str = Field(description="Message author role: system, user, or assistant")
    content: str = Field(description="Message textual content")


class LlmUsage(BaseModel):
    """Token consumption metadata."""

    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)


class LlmResponse(BaseModel):
    """Output generated by an LLM provider."""

    content: str = Field(description="Generated textual completion")
    model: str = Field(description="Exact provider model that served the request")
    usage: LlmUsage = Field(default_factory=LlmUsage)
    finish_reason: Optional[str] = Field(default=None)


class BaseLlmProvider(ABC):
    """Abstract interface implemented by all LLM inference providers."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Provider identifier (e.g., 'openai', 'deterministic')."""
        pass

    @property
    @abstractmethod
    def model(self) -> str:
        """Active model identifier."""
        pass

    @property
    @abstractmethod
    def is_external(self) -> bool:
        """True if requests leave local infrastructure (data-egress flag)."""
        pass

    @abstractmethod
    async def generate(
        self,
        messages: List[LlmMessage],
        max_tokens: Optional[int] = None,
        temperature: float = 0.0,
    ) -> LlmResponse:
        """Generate a response given an ordered sequence of messages."""
        pass
