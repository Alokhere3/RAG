"""Pydantic schemas for RAG query requests, citations, and grounded answers."""

import uuid
from typing import List, Optional
from pydantic import BaseModel, Field, model_validator

from app.services.llm.base import LlmUsage


class Citation(BaseModel):
    """Reference to an authorized source chunk used to ground an answer."""

    document_id: uuid.UUID = Field(description="Source document identifier")
    document_title: str = Field(description="Source document display title")
    chunk_id: uuid.UUID = Field(description="Specific chunk UUID")
    chunk_index: int = Field(description="0-indexed position within source document")
    relevance_score: float = Field(description="Vector cosine similarity score [0.0 - 1.0]")
    snippet: str = Field(description="Excerpt of the chunk content")
    char_offset_start: Optional[int] = Field(
        default=None,
        description="Optional start character offset of excerpt within source chunk content",
    )
    char_offset_end: Optional[int] = Field(
        default=None,
        description="Optional end character offset of excerpt within source chunk content",
    )

    @model_validator(mode="after")
    def validate_passage_offsets(self) -> "Citation":
        """Validate character offsets when provided."""
        start = self.char_offset_start
        end = self.char_offset_end
        if start is not None and end is not None:
            if start < 0:
                raise ValueError(f"char_offset_start cannot be negative: {start}")
            if end < start:
                raise ValueError(
                    f"char_offset_end ({end}) cannot be less than char_offset_start ({start})"
                )
        elif (start is None) != (end is None):
            raise ValueError("Both char_offset_start and char_offset_end must be provided together")
        return self


class RagQueryRequest(BaseModel):
    """Request payload to query the RAG engine."""

    query: str = Field(min_length=1, max_length=2000, description="User question or query")
    limit: int = Field(default=5, ge=1, le=20, description="Max number of candidate chunks to retrieve")
    similarity_threshold: float = Field(default=0.20, ge=0.0, le=1.0, description="Minimum similarity score")


class RagAnswer(BaseModel):
    """Grounded response generated by the RAG engine."""

    answer: str = Field(description="Grounded response text")
    citations: List[Citation] = Field(default_factory=list, description="Verified source citations")
    insufficient_evidence: bool = Field(default=False, description="True if no reliable sources were found")
    retrieved_chunks_count: int = Field(default=0, description="Number of authorized chunks retrieved")
    latency_ms: float = Field(description="End-to-end execution latency in milliseconds")
    usage: Optional[LlmUsage] = Field(default=None, description="Token usage statistics if available")
    model: str = Field(description="LLM model identifier used for generation")
